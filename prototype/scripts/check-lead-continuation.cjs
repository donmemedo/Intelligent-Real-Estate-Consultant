const assert = require("node:assert/strict");
const { mkdtempSync } = require("node:fs");
const { tmpdir } = require("node:os");
const { join } = require("node:path");
const { execFileSync } = require("node:child_process");
const out = mkdtempSync(join(tmpdir(), "lead-continuation-"));
execFileSync(process.execPath, [require.resolve("typescript/bin/tsc"), "lib/lead-continuation.ts", "--outDir", out, "--module", "commonjs", "--target", "ES2017", "--skipLibCheck"], { cwd: join(__dirname, ".."), stdio: "inherit" });
const { initialContinuation, correctContinuation, parseContinuation, continuationKey, rejectionExample, resetContinuationStorage } = require(join(out, "lead-continuation.js"));
const lead = { messages: [{ id: "m1", from: "lead", text: "Not this quarter. Send me something if the payment plan is genuinely good.", channel: "Voice", time: "Yesterday · 4:12 PM" }] };
const before = JSON.stringify(lead);
const [note] = initialContinuation(lead);
assert.equal(note.evidence.quote, lead.messages[0].text);
assert.equal(note.evidence.messageId, "m1");
assert.deepEqual(initialContinuation({ messages: [] }), []);
assert.deepEqual(initialContinuation({ messages: [{ ...lead.messages[0], from: "agent" }] }), []);
const revised = correctContinuation(note, " Needs clarification on timing ", "Needs clarification", " Confirm exact quarter ", "2026-09-24T09:00:00Z");
assert.equal(note.history.length, 0);
assert.deepEqual(revised.evidence, note.evidence);
assert.equal(revised.history[0].before, note.text);
assert.equal(revised.history[0].reason, "Confirm exact quarter");
const second = correctContinuation(revised, "Timing confirmed", "Resolved", "Customer clarification", "2026-09-24T10:00:00Z");
assert.equal(second.history.length, 2);
assert.equal(second.history[1].previousState, "Needs clarification");
assert.throws(() => correctContinuation(note, "x", "Resolved", " ", "now"));
assert.throws(() => correctContinuation(note, " ", "Resolved", "reason", "now"));
assert.throws(() => correctContinuation(note, "x", "Bad", "reason", "now"));
assert.deepEqual(parseContinuation(JSON.stringify([second])), [second]);
for (const raw of ["bad", "{}", "[null]", '[{"id":"x"}]']) assert.throws(() => parseContinuation(raw));
assert.notEqual(continuationKey("sample", "a"), continuationKey("sample", "b"));
assert.notEqual(continuationKey("sample", "a"), continuationKey("other", "a"));
assert.equal(rejectionExample().evidence.messageId, undefined);
assert.match(rejectionExample().evidence.time, /Illustrative/);
assert.match(rejectionExample().property, /^Hills Park/);
assert.match(rejectionExample().evidence.quote, /Hills Park/);
const scope = "propagent-demo-leads-v2";
const saved = new Map([[scope, "founder lead state"], [continuationKey(scope, "a"), "a"], [continuationKey(scope, "b"), "b"], [continuationKey("other", "a"), "other"]]);
const access = () => ({ removeItem: key => saved.delete(key) });
assert.equal(resetContinuationStorage(access, scope, ["a", "b"]), true);
assert.equal(saved.get(scope), "founder lead state");
assert.equal(saved.get(continuationKey("other", "a")), "other");
assert.equal(resetContinuationStorage(() => { throw Error("denied"); }, scope, ["a"]), false);
assert.equal(resetContinuationStorage(() => { throw Error("denied"); }, null, ["a"]), true);
assert.equal(JSON.stringify(lead), before);
console.log("PASS: evidence preserved, corrections append history, invalid data rejected, notes isolated from lead state");
