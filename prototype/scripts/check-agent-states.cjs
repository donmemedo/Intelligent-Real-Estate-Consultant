const assert = require("node:assert/strict");
const { mkdtempSync } = require("node:fs");
const { tmpdir } = require("node:os");
const { join } = require("node:path");
const { execFileSync } = require("node:child_process");
const out = mkdtempSync(join(tmpdir(), "agent-states-"));
execFileSync(process.execPath, [require.resolve("typescript/bin/tsc"), "lib/agent-state.ts", "lib/home-state.ts", "lib/prototype-data.ts", "lib/demo-leads.ts", "--outDir", out, "--module", "commonjs", "--target", "ES2017", "--skipLibCheck"], { cwd: join(__dirname, ".."), stdio: "inherit" });
const { getAgentWorkspaceState } = require(join(out, "agent-state.js"));
const empty = { selected: 0, completed: [], values: {} };
assert.equal(getAgentWorkspaceState("whatsapp-agent", empty).label, "Needs setup");
assert.equal(getAgentWorkspaceState("voice-agent", empty).label, "Live use blocked");
assert.equal(getAgentWorkspaceState("email-agent", empty).label, "Planned");
assert.equal(getAgentWorkspaceState("manager-agent", empty).label, "Ready to explore");
const configured = { selected: 7, completed: ["whatsapp", "knowledge"], values: { whatsapp: "Agency number", knowledge: "Approved sheet" } };
assert.equal(getAgentWorkspaceState("whatsapp-agent", configured).label, "Ready to test");
const invalid = { ...configured, values: { ...configured.values, knowledge: "" } };
assert.equal(getAgentWorkspaceState("whatsapp-agent", invalid).setupStep, "knowledge");
assert.deepEqual(configured.values, { whatsapp: "Agency number", knowledge: "Approved sheet" });
console.log("PASS: agent readiness, blockers, scope and setup validation");
